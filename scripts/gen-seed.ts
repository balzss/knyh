/**
 * Builds db/seed.sql from db/seed-data.json.
 * Run with: npm run db:gen-seed
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { isValidDatabaseSchema, normalizeImportData } from '../src/lib/import-validation'

const raw = JSON.parse(readFileSync('db/seed-data.json', 'utf8'))
if (!isValidDatabaseSchema(raw)) throw new Error('db/seed-data.json is not a valid library file')
const data = normalizeImportData(raw)

const q = (value: string | null | undefined) =>
  value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`

const tagIds = new Set(data.tags.map((tag) => tag.id))
const lines: string[] = ['-- Generated by scripts/gen-seed.ts. Do not edit by hand.']

for (const tag of data.tags) {
  lines.push(`INSERT INTO tags (id, display_name) VALUES (${q(tag.id)}, ${q(tag.displayName)});`)
}
for (const recipe of data.recipes) {
  lines.push(
    `INSERT INTO recipes (id, title, ingredients, instructions, total_time, yield, archived, created_at, updated_at) VALUES (` +
      [
        q(recipe.id),
        q(recipe.title),
        q(JSON.stringify(recipe.ingredients)),
        q(JSON.stringify(recipe.instructions)),
        q(recipe.totalTime),
        q(recipe.yield),
        recipe.archived ? 1 : 0,
        q(new Date(recipe.createdAt).toISOString()),
        q(new Date(recipe.updatedAt).toISOString()),
      ].join(', ') +
      ');'
  )
  for (const tag of recipe.tags.filter((t) => tagIds.has(t.id))) {
    lines.push(
      `INSERT INTO recipe_tags (recipe_id, tag_id) VALUES (${q(recipe.id)}, ${q(tag.id)});`
    )
  }
}
for (const key of ['name', 'language'] as const) {
  const value = data.userConfig[key]
  if (value !== undefined) {
    lines.push(`INSERT INTO config (key, value) VALUES (${q(key)}, ${q(String(value))});`)
  }
}

writeFileSync('db/seed.sql', lines.join('\n') + '\n')
console.log(`Wrote db/seed.sql: ${data.recipes.length} recipes, ${data.tags.length} tags`)
